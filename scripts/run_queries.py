"""Run the example queries in queries/ over usdm-rdf plus the overlay.

Input:  downloads/usdm_v4.ttl, usdm_overlay.ttl, derived/*.ttl, authored/*.ttl
        queries/*.rq
Output: reports/queries.md

A query that returns no rows stops the run.
"""
from rdflib import Graph

from common import DOWNLOADS, ROOT, local


def cell(value):
    if value is None:
        return ""
    text = str(value)
    if text.startswith("http"):
        return local(text)
    return text.replace("|", "\\|")


def main():
    g = Graph().parse(DOWNLOADS / "usdm_v4.ttl")
    g.parse(ROOT / "usdm_overlay.ttl")
    for folder in ("derived", "authored"):
        for f in sorted((ROOT / folder).glob("*.ttl")):
            g.parse(f)

    lines = [
        "# Example queries",
        "",
        "Generated by `scripts/run_queries.py` over usdm-rdf v0.7.1 plus the overlay graphs. Do not edit by hand.",
        "",
        "Each query uses the effective assessment of a term: the one no other assessment refines.",
    ]
    for q in sorted((ROOT / "queries").glob("*.rq")):
        text = q.read_text()
        result = g.query(text)
        rows = list(result)
        if not rows:
            raise RuntimeError(f"{q.name} returned no rows")
        comment = " ".join(l.lstrip("# ").strip() for l in text.splitlines() if l.startswith("#"))
        names = [str(v) for v in result.vars]
        lines += ["", f"## {q.name}", "", comment, "", f"{len(rows)} rows.", ""]
        lines.append("| " + " | ".join(names) + " |")
        lines.append("| " + " | ".join("---" for _ in names) + " |")
        for row in rows:
            lines.append("| " + " | ".join(cell(v) for v in row) + " |")
    (ROOT / "reports" / "queries.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
